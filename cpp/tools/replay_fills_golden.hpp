inline iap::ExecConfig golden_exec_config(const std::string& configs_dir) {
    iap::ExecConfig cfg;
    cfg.seed = 20260829;
    cfg.impact_coeff_bps_per_pct_adv = 2.0;
    cfg.venues = iap::load_venues(configs_dir + "/venues/venues.json");
    iap::InstrumentSpec ins;
    ins.instrument_id = 1;
    ins.tick_size = 0.01;
    ins.qty_unit = 1.0;
    ins.adv = 38000000.0;
    cfg.instruments[1] = ins;
    return cfg;
}

inline iap::ParentOrder golden_parent(std::uint64_t parent_id,
                                      std::uint16_t venue_id, std::uint8_t side,
                                      std::int64_t qty, iap::AlgoType algo,
                                      std::int64_t start_ts, std::int64_t end_ts) {
    iap::ParentOrder p;
    p.parent_id = parent_id;
    p.instrument_id = 1;
    p.venue_id = venue_id;
    p.side = side;
    p.qty = qty;
    p.algo = algo;
    p.start_ts = start_ts;
    p.end_ts = end_ts;
    return p;
}

inline std::vector<iap::ParentOrder> native_parents(std::int64_t t0) {
    constexpr std::int64_t kSec = 1'000'000'000;
    iap::ParentOrder vwap = golden_parent(1, 1, 0, 400, iap::AlgoType::VWAP,
                                          t0 + 60 * kSec, t0 + 660 * kSec);
    vwap.slices = 4;
    iap::ParentOrder is = golden_parent(2, 1, 1, 600, iap::AlgoType::IS,
                                        t0 + 120 * kSec, t0 + 720 * kSec);
    is.slices = 3;
    is.risk_aversion = 1.0;
    return {vwap, is};
}

inline std::vector<iap::ParentOrder> passive_parents(std::int64_t t0) {
    constexpr std::int64_t kSec = 1'000'000'000;
    iap::ParentOrder vwap = golden_parent(1, 1, 0, 400, iap::AlgoType::VWAP,
                                          t0 + 60 * kSec, t0 + 660 * kSec);
    vwap.slices = 4;
    vwap.policy = iap::ExecPolicy::PASSIVE;
    vwap.urgency = 0.5;
    iap::ParentOrder is = golden_parent(2, 1, 1, 600, iap::AlgoType::IS,
                                        t0 + 120 * kSec, t0 + 720 * kSec);
    is.slices = 3;
    is.risk_aversion = 1.0;
    is.policy = iap::ExecPolicy::PASSIVE;
    is.urgency = 0.2;
    iap::ParentOrder pov = golden_parent(3, 0, 0, 300, iap::AlgoType::POV,
                                         t0 + 90 * kSec, t0 + 690 * kSec);
    pov.participation = 0.1;
    pov.policy = iap::ExecPolicy::PASSIVE;
    pov.urgency = 0.0;
    iap::ParentOrder twap = golden_parent(4, 1, 1, 200, iap::AlgoType::TWAP,
                                          t0 + 150 * kSec, t0 + 450 * kSec);
    twap.slices = 4;
    twap.policy = iap::ExecPolicy::AGGRESSIVE;
    return {vwap, is, pov, twap};
}

// printf("%.17g") of a double (round-trip exact).
inline std::string g17(double x) {
    char buf[64];
    std::snprintf(buf, sizeof(buf), "%.17g", x);
    return std::string(buf);
}

// The golden document. `with_passive` appends the PASSIVE transition
// counters (policy golden only; the NATIVE golden has no such block).
inline std::string render_replay_fills(const iap::ExecReplayResult& res,
                                       std::int64_t t0, int x_version,
                                       const std::string& description,
                                       bool with_passive) {
    using std::to_string;
    std::string out = "{\n  \"x-version\": " + to_string(x_version) + ",\n";
    out += "  \"description\": \"" + description + "\",\n";
    out += "  \"seed\": 20260829,\n";
    out += "  \"t0\": " + to_string(t0) + ",\n";
    out += "  \"events_processed\": " + to_string(res.events_processed) + ",\n";
    out += "  \"fills\": [\n";
    for (std::size_t i = 0; i < res.fills.size(); ++i) {
        const iap::Fill& x = res.fills[i];
        out += "    {\"fill_id\": " + to_string(x.fill_id);
        out += ", \"order_id\": " + to_string(x.order_id);
        out += ", \"parent_id\": " + to_string(x.parent_id);
        out += ", \"instrument_id\": " + to_string(x.instrument_id);
        out += ", \"venue_id\": " + to_string(static_cast<unsigned>(x.venue_id));
        out += ", \"side\": " + to_string(static_cast<unsigned>(x.side));
        out += ", \"price_ticks\": " + to_string(x.price_ticks);
        out += ", \"qty\": " + to_string(x.qty);
        out += ", \"ts\": " + to_string(x.ts);
        out += ", \"liquidity\": \"";
        out += x.liquidity == iap::Liquidity::MAKER ? "MAKER" : "TAKER";
        out += "\", \"fee\": " + g17(x.fee);
        out += ", \"impact_cost\": " + g17(x.impact_cost) + "}";
        out += i + 1 < res.fills.size() ? ",\n" : "\n";
    }
    out += "  ],\n  \"parents\": {\n";
    std::size_t np = 0;
    for (const auto& [pid, r] : res.parents) {
        out += "    \"" + to_string(pid) + "\": {\"filled_qty\": " +
               to_string(r.filled_qty);
        out += ", \"unfilled_qty\": " + to_string(r.unfilled_qty);
        out += ", \"children\": " + to_string(r.children);
        out += ", \"notional\": " + g17(r.notional);
        out += ", \"avg_price\": " + g17(r.avg_price);
        out += ", \"fees\": " + g17(r.fees);
        out += ", \"rebates\": " + g17(r.rebates);
        out += ", \"impact\": " + g17(r.impact);
        out += ", \"total_cost\": " + g17(r.total_cost) + "}";
        out += ++np < res.parents.size() ? ",\n" : "\n";
    }
    if (!with_passive) {
        out += "  }\n}\n";
        return out;
    }
    out += "  },\n  \"passive\": {\n";
    std::size_t ns = 0;
    for (const auto& [pid, s] : res.passive) {
        out += "    \"" + to_string(pid) + "\": {\"posts\": " + to_string(s.posts);
        out += ", \"reprices\": " + to_string(s.reprices);
        out += ", \"rest_extensions\": " + to_string(s.rest_extensions);
        out += ", \"crosses_timeout\": " + to_string(s.crosses_timeout);
        out += ", \"crosses_behind\": " + to_string(s.crosses_behind);
        out += ", \"crosses_immediate\": " + to_string(s.crosses_immediate) + "}";
        out += ++ns < res.passive.size() ? ",\n" : "\n";
    }
    out += "  }\n}\n";
    return out;
}

