// Scenarios and writer of the two execution-replay goldens — shared by the
// generator (make_replay_fills_golden.cpp) and by
// tests/test_replay_fills_passive.cpp, which renders both documents in
// memory and compares them with the committed files byte for byte.
//
//   tests/golden/expected_replay_fills.json          (x-version 2, NATIVE)
//     parent 1: VWAP BUY 400 over [t0+60s, t0+660s), 4 slices, passive LIMIT
//               children joining the best bid at each slice decision;
//     parent 2: IS   SELL 600 over [t0+120s, t0+720s), 3 slices,
//               risk_aversion 1.0, aggressive MARKET children.
//   tests/golden/expected_replay_fills_passive.json  (x-version 1, policies)
//     parent 1: VWAP BUY  400, same window and slices, PASSIVE, urgency 0.5;
//     parent 2: IS   SELL 600, same window and slices, PASSIVE, urgency 0.2;
//     parent 3: POV  BUY  300 over [t0+90s, t0+690s), participation 0.1,
//               PASSIVE, urgency 0.0, SOR-routed (venue_id 0);
//     parent 4: TWAP SELL 200 over [t0+150s, t0+450s), 4 slices, AGGRESSIVE.
//
// Config of both: seed 20260829, latency decision/risk/wire 50/50/100 us +
// XV1 venue latency (mean 150 us, jitter uniform [0, 50 us], SplitMix64),
// impact_coeff_bps_per_pct_adv 2.0, instrument 1 adv 38,000,000 lot 1.0
// (fees per share); PASSIVE parameters = the PassiveParams defaults. The
// fill list is exact (ticks/qty/ts); fee and impact_cost are doubles
// printed with %.17g (round-trip exact). The policy golden is committed
// from python/tools/make_golden_replay_passive.py, which writes the same
// bytes.

