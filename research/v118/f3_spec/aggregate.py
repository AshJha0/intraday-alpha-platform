"""F3 spec pilot: aggregate cell JSONs, apply the plan's section-6 rule mechanically, write results.

  python aggregate.py out_dir RESULTS_MD SUMMARY_JSON
EXPLORATORY; not acceptance evidence.
"""

from __future__ import annotations

import json
import math
import sys
from pathlib import Path

from scipy import stats

MANDATORY = ("a0", "b0", "b1")
GS = (5, 7, 10)
PROCS = ("P0", "P1", "P2", "P3")
SIMPLICITY = {"P1": 0, "P2": 1, "P0": 2, "P3": 2}
LIM = {"1": 1.10, "3": 1.10, "6": 1.10, "16": 1.20}


def cp_upper(k: int, n: int, conf: float = 0.95) -> float:
    return 1.0 if k >= n else float(stats.beta.ppf(conf, k + 1, n - k))


def pass_table(n: int = 50000, target: float = 0.025) -> list[dict]:
    kmax = max(k for k in range(0, int(n * target) + 1) if cp_upper(k, n) <= target)
    rows = [
        {"true_fwer": p, "pass_prob": float(stats.binom.cdf(kmax, n, p))}
        for p in (0.015, 0.018, 0.020, 0.021, 0.022, 0.023, 0.0235, 0.024, 0.0245, 0.025)
    ]
    lo, hi = 0.01, 0.025
    for _ in range(60):  # true FWER at which pass probability is 95 %
        mid = (lo + hi) / 2
        if stats.binom.cdf(kmax, n, mid) > 0.95:
            lo = mid
        else:
            hi = mid
    return [
        {
            "n": n,
            "kmax": kmax,
            "max_empirical_rate": kmax / n,
            "fwer_certifiable_at_95pct_pass": lo,
        },
        *rows,
    ]


def load(d: Path) -> dict:
    cells = {}
    for f in sorted(d.glob("*_G*.json")):
        r = json.loads(f.read_text())
        cells[(r["regime"], r["G"])] = r
    return cells


def main(d: str, md: str, sj: str) -> None:
    cells = load(Path(d))
    elig = {}
    for p in PROCS:
        reasons, logs, a0r = [], [], []
        for reg in MANDATORY:
            for g in GS:
                c = cells.get((reg, g))
                if c is None:
                    reasons.append(f"missing {reg} G{g}")
                    continue
                s = c["procedures"][p]
                if s["failures"] > 0 or s["info"].get("df_nonfinite", 0) > 0:
                    reasons.append(f"failures {reg} G{g}")
                for k, lim in LIM.items():
                    r = s["marginal"][k]["ratio"]
                    if r > lim:
                        reasons.append(f"{reg} G{g} k{k} ratio {r:.2f}>{lim}")
                    if r > 0:
                        logs.append(abs(math.log(r)))
                    if reg == "a0" and k in ("1", "3", "6"):
                        a0r.append(r)
                for kf in ("3", "6", "16"):
                    fw = s["fwer"][f"0.025_K{kf}"]["rate"]
                    if fw > 0.0275:
                        reasons.append(f"{reg} G{g} FWER K{kf} {fw:.4f}>0.0275")
        calib = not reasons
        conservative = bool(a0r) and (sum(a0r) / len(a0r) < 0.70)
        elig[p] = {
            "calibrated": calib,
            "too_conservative": conservative,
            "mean_a0_ratio_k136": (sum(a0r) / len(a0r)) if a0r else None,
            "max_abs_log_ratio": max(logs) if logs else None,
            "reasons": reasons,
        }
    cand = [p for p in PROCS if elig[p]["calibrated"] and not elig[p]["too_conservative"]]
    cand.sort(key=lambda p: (SIMPLICITY[p], elig[p]["max_abs_log_ratio"]))
    chosen = cand[0] if cand else None

    L = ["# F3 spec pilot results (EXPLORATORY, synthetic, NOT acceptance evidence)", ""]
    L.append(
        "Generated by `research/v118/f3_spec/aggregate.py` from `out/*.json`. Rule = plan section 6, applied mechanically."
    )
    L.append("")
    L.append(f"**Rule outcome: {'chosen = ' + chosen if chosen else 'NO procedure eligible'}**")
    L.append("")
    L.append(
        "| proc | calibrated (all mandatory cells) | too conservative | mean a0 ratio (k=1,3,6) | max abs log ratio | first reasons |"
    )
    L.append("|---|---|---|---|---|---|")
    for p in PROCS:
        e = elig[p]
        L.append(
            f"| {p} | {e['calibrated']} | {e['too_conservative']} | {e['mean_a0_ratio_k136']:.3f} | "
            f"{e['max_abs_log_ratio']:.3f} | {'; '.join(e['reasons'][:4])} |"
            if e["mean_a0_ratio_k136"] is not None
            else f"| {p} | missing | | | | |"
        )
    L.append("")
    L.append(
        "## Marginal size ratio (observed rate / nominal) of raw p <= 0.025/k, pooled over the 16 hypotheses"
    )
    L.append(
        "Wilson 95 % half-width relative: about 6 % (k=1 ~3 %, k=3-6 ~6 %, k=16 ~10 %) for independent-hypothesis cells with 6,000 datasets."
    )
    L.append("")
    L.append("| regime | G | proc | k=1 | k=3 | k=6 | k=16 | FWER K3 | K6 | K16 | cpu s/1000 ds |")
    L.append("|---|---|---|---|---|---|---|---|---|---|---|")
    for reg in ("a0", "a1", "b0", "b1", "c0", "c1"):
        for g in GS:
            c = cells.get((reg, g))
            if not c:
                continue
            for p in PROCS:
                s = c["procedures"][p]
                m = s["marginal"]
                f = s["fwer"]
                L.append(
                    f"| {reg} | {g} | {p} | {m['1']['ratio']:.2f} | {m['3']['ratio']:.2f} | {m['6']['ratio']:.2f} | "
                    f"{m['16']['ratio']:.2f} | {f['0.025_K3']['rate']:.4f} | {f['0.025_K6']['rate']:.4f} | "
                    f"{f['0.025_K16']['rate']:.4f} | {s['cpu_s_per_1000_datasets']:.2f} |"
                )
    L.append("")
    L.append(
        "FWER columns are at alpha = 0.025 (n = datasets, Wilson half-width about 0.4 pp). Rates at alpha = 0.020 are in the cell JSONs."
    )
    L.append("")
    pt = pass_table()
    L.append(
        "## Pass probability of the future rule (one-sided 95 % Clopper-Pearson UCB <= 2.5 %, n = 50,000)"
    )
    L.append(
        f"Largest passing count k = {pt[0]['kmax']} ({pt[0]['max_empirical_rate']:.5f}); true FWER at which the pass "
        f"probability is exactly 95 %: {pt[0]['fwer_certifiable_at_95pct_pass']:.4f}."
    )
    L.append("")
    L.append("| true FWER | P(pass) |")
    L.append("|---|---|")
    for r in pt[1:]:
        L.append(f"| {r['true_fwer']:.4f} | {r['pass_prob']:.4f} |")
    Path(md).write_text("\n".join(L) + "\n", encoding="utf-8")
    Path(sj).write_text(
        json.dumps({"chosen": chosen, "eligibility": elig, "pass_table": pt}, indent=1)
    )
    print("chosen:", chosen)


if __name__ == "__main__":
    main(*sys.argv[1:4])
