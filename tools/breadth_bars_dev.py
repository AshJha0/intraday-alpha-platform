#!/usr/bin/env python3
"""Round 1 development study: a several-hundred-name 15-minute book on one-minute
bars of one Nasdaq ITCH day (iap.research.breadth_bars).  Exploratory, one session.

    gzip -dc data/vendor/01302019.NASDAQ_ITCH50.gz | itchbars > data/real/bars/bars_20190130.csv
    python tools/breadth_bars_dev.py --bars data/real/bars/bars_20190130.csv --date 2019-01-30

Every parameter below was fixed before the first run and is not an option:
universe top 500, price floor 5 dollars, quote coverage 95 %; lookback, step and
horizon 15 minutes; primary entry delay 1 minute, with delay 0 as the declared
diagnostic.  Two scores at two delays are four looks; the report counts them.
Writes research/round1/breadth_bars_<date>.json, BREADTH_BARS_<date>.md and
universe_<date>.json.
"""

from __future__ import annotations

import argparse
import hashlib
import json
import math
import sys
from pathlib import Path

import numpy as np

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT / "python" / "src"))

from iap.research import breadth_bars as bb  # noqa: E402
from iap.research.pnl_power import mde_sharpe  # noqa: E402
from iap.validation.sessions import day_tags  # noqa: E402

TOP, MIN_PRICE, MIN_QUOTE = 500, 5.0, 0.95
LOOKBACK = STEP = HORIZON = 15
DELAYS = (1, 0)  # primary first


def _sha256(path: Path) -> str:
    h = hashlib.sha256()
    with path.open("rb") as fh:
        for chunk in iter(lambda: fh.read(1 << 22), b""):
            h.update(chunk)
    return h.hexdigest()


def _clean(obj):
    if isinstance(obj, dict):
        return {k: _clean(v) for k, v in obj.items()}
    if isinstance(obj, list):
        return [_clean(v) for v in obj]
    if isinstance(obj, float) and not math.isfinite(obj):
        return None
    return obj


def _f(v, nd=2) -> str:
    return "n/a" if v is None or not math.isfinite(v) else f"{v:.{nd}f}"


def render(doc: dict) -> str:
    u, d = doc["universe"], doc["date"]
    lines = [
        f"# Breadth on bars, {d}: development study (exploratory, one session, no edge claim)",
        "",
        "Generated by `tools/breadth_bars_dev.py` from the `itchbars` bars of the day; rerun it,",
        "do not edit by hand. Every parameter was fixed before the first run.",
        "",
        "**The plain idea.** Does a 15-minute cross-sectional reversal score earn more than the",
        "quoted spread on several hundred names? One session cannot answer that; it can show the",
        "size of the gross effect against the size of the cost, which says where to look next.",
        "",
        "## Data and universe",
        "",
        f"- Bars file sha256 `{doc['bars_sha256']}`; {doc['symbols_in_file']:,} symbols.",
        f"- Rule: {u['rule']}",
        f"- Eligible {u['eligible']:,}; universe {u['names']}; rank 1 {u['first']}, last {u['last']}.",
        f"- Universe median mid {_f(u['median_mid'])} dollars; median quoted spread "
        f"{_f(u['median_spread_bps'])} bps (one venue's quote); median displayed notional "
        f"{u['median_notional']:,.0f} dollars.",
        "",
        "## Results (bps per rebalance on gross; mean, standard error, Student t over rebalances)",
        "",
        "| delay | score | rebalances | rank IC | IC t | gross | gross t | net of spread | net t |",
        "|---|---|---:|---:|---:|---:|---:|---:|---:|",
    ]
    for run in doc["runs"]:
        for s, r in run["scores"].items():
            ic, g, n = r["rank_ic"], r["gross_bps_per_rebalance"], r["net_bps_per_rebalance"]
            lines.append(
                f"| {run['params']['delay']} min | {s} | {ic['n']} | {_f(ic['mean'], 4)} | "
                f"{_f(ic['t'])} | {_f(g['mean'])} | {_f(g['t'])} | {_f(n['mean'])} | {_f(n['t'])} |"
            )
    lines += [
        "",
        f"Median round-trip spread cost in the universe: "
        f"{_f(doc['runs'][0]['median_round_trip_cost_bps'])} bps.",
        "",
        "## How to read it",
        "",
        "- The t values are across the rebalances of ONE session. They are not independent across",
        "  days and carry no confirmation weight: the independent unit is the session.",
        f"- Session tags from the event calendar: {', '.join(doc['session_tags']) or 'none'}. An event day",
        "  is not a typical session.",
        f"- Looks taken here: {doc['looks']} (two scores, two entry delays), recorded in",
        "  `research/round1/looks_ledger.json` with the round's other looks. The 1-minute delay is",
        "  the primary; delay 0 assumes a trade at the quote the decision was made on.",
        "- Costs: the book crosses the quoted spread to enter and to exit and turns over fully",
        "  each rebalance. No fee, no impact, no borrow. Nasdaq's own quote is wider than the",
        "  consolidated one, so the spread cost is overstated; the missing fee and impact go the",
        "  other way.",
        f"- Power: one session detects nothing. {doc['power']['sessions_listed']} sessions would",
        f"  detect a net Sharpe of about {_f(doc['power']['mde_sharpe'], 1)} or more "
        "(`docs/research/PNL_POWER_TABLE.md`).",
        "",
    ]
    return "\n".join(lines)


def main(argv: list[str] | None = None) -> int:
    ap = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    ap.add_argument("--bars", type=Path, required=True)
    ap.add_argument("--date", required=True, help="session date, YYYY-MM-DD")
    ap.add_argument("--out-dir", type=Path, default=ROOT / "research" / "round1")
    args = ap.parse_args(argv)

    panel = bb.load_panel(args.bars)
    rows = bb.select_universe(panel, TOP, MIN_PRICE, MIN_QUOTE)
    all_rows = bb.select_universe(panel, len(panel.symbols), MIN_PRICE, MIN_QUOTE)
    with np.errstate(all="ignore"):
        med_mid = np.nanmedian(panel.mid[rows], axis=1)
        med_spread = np.nanmedian(2e4 * panel.half_spread[rows], axis=1)
    notional = panel.notional[rows].sum(axis=1)
    names = [panel.symbols[i] for i in rows]
    universe = {
        "rule": bb.UNIVERSE_RULE.format(min_price=MIN_PRICE, min_quote_frac=MIN_QUOTE, top=TOP),
        "eligible": len(all_rows),
        "names": len(rows),
        "first": names[0],
        "last": names[-1],
        "median_mid": float(np.median(med_mid)),
        "median_spread_bps": float(np.median(med_spread)),
        "median_notional": float(np.median(notional)),
    }
    runs = [bb.run_study(panel, rows, LOOKBACK, STEP, HORIZON, d) for d in DELAYS]
    sessions_listed = 10
    doc = {
        "schema": "iap.round1.breadth_bars_dev/1",
        "date": args.date,
        "bars_sha256": _sha256(args.bars),
        "symbols_in_file": len(panel.symbols),
        "universe": universe,
        "looks": len(DELAYS) * len(bb.SCORES),
        "runs": runs,
        "power": {
            "sessions_listed": sessions_listed,
            "mde_sharpe": mde_sharpe(sessions_listed),
        },
        "evidence_class": "exploratory",
        "session_tags": sorted(day_tags(args.date)),
    }
    doc = _clean(doc)
    args.out_dir.mkdir(parents=True, exist_ok=True)
    tag = args.date.replace("-", "")
    (args.out_dir / f"universe_{tag}.json").write_text(
        json.dumps({"date": args.date, "rule": universe["rule"], "symbols": names}, indent=1)
        + "\n",
        encoding="utf-8",
        newline="\n",
    )
    (args.out_dir / f"breadth_bars_{tag}.json").write_text(
        json.dumps(doc, indent=1, sort_keys=True) + "\n", encoding="utf-8", newline="\n"
    )
    (args.out_dir / f"BREADTH_BARS_{tag}.md").write_text(
        render(doc), encoding="utf-8", newline="\n"
    )
    print(render(doc))
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
