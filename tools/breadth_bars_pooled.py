#!/usr/bin/env python3
"""Round 1 pooled development study: the 500-name 15-minute book of
tools/breadth_bars_dev.py on every in-sample session that has bars, with the
verdict taken across sessions (iap.research.breadth_bars.pool_sessions).

    python tools/breadth_bars_pooled.py [--bars-dir data/real/bars]

The universe is the one fixed on 2019-01-30 (research/round1/universe_20190130.json);
it is not re-selected on other days, and names missing on a day are counted.
Parameters are those of the one-session study and are not options.  Writes
research/round1/breadth_bars_pooled.json and BREADTH_BARS_POOLED.md.
"""

from __future__ import annotations

import argparse
import json
import math
import re
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT / "python" / "src"))

from iap.research import breadth_bars as bb  # noqa: E402
from iap.research.pnl_power import mde_sharpe  # noqa: E402
from iap.validation.sessions import day_tags  # noqa: E402

LOOKBACK = STEP = HORIZON = 15
DELAYS = (1, 0)  # primary first
UNIVERSE = ROOT / "research" / "round1" / "universe_20190130.json"
HOLDOUT_FROM = "2025-01-01"


def _f(v, nd=2) -> str:
    return "n/a" if v is None or not math.isfinite(v) else f"{v:.{nd}f}"


def _clean(obj):
    if isinstance(obj, dict):
        return {k: _clean(v) for k, v in obj.items()}
    if isinstance(obj, list):
        return [_clean(v) for v in obj]
    if isinstance(obj, float) and not math.isfinite(obj):
        return None
    return obj


def session_files(bars_dir: Path) -> dict[str, Path]:
    out = {}
    for p in sorted(bars_dir.glob("bars_*.csv")):
        m = re.fullmatch(r"bars_(\d{4})(\d{2})(\d{2})\.csv", p.name)
        if not m:
            continue
        date = "-".join(m.groups())
        if date >= HOLDOUT_FROM:
            raise SystemExit(f"refusing {p.name}: sessions from 2025 on are the sealed holdout")
        out[date] = p
    return out


def render(doc: dict) -> str:
    lines = [
        "# Breadth on bars, pooled in-sample sessions (exploratory, no edge claim)",
        "",
        "Generated by `tools/breadth_bars_pooled.py`; rerun it, do not edit by hand. Universe fixed",
        "on 2019-01-30, parameters fixed before the first run (`BREADTH_BARS_20190130.md`).",
        "",
        "**The plain idea.** One number per session and per score: the mean net return of the",
        "decile book per 15-minute rebalance. The test is across sessions, because sessions are",
        "the independent unit.",
        "",
        f"Sessions: {len(doc['sessions'])}. Looks: {doc['looks']} (two scores, two entry delays, "
        "each session a new look), not yet in `research/experiments.json`.",
        "",
        "## Across sessions (bps per rebalance; Student t on sessions - 1 degrees of freedom)",
        "",
        "| delay | score | sessions | mean rank IC | IC t | gross | gross t | net of spread | "
        "net t | sessions net > 0 |",
        "|---|---|---:|---:|---:|---:|---:|---:|---:|---:|",
    ]
    for key, row in doc["pooled"].items():
        delay, score = key.split("|")
        ic, g, n = row["rank_ic"], row["gross_bps"], row["net_bps"]
        lines.append(
            f"| {delay} min | {score} | {n['n']} | {_f(ic['mean'], 4)} | {_f(ic['t'])} | "
            f"{_f(g['mean'])} | {_f(g['t'])} | {_f(n['mean'])} | {_f(n['t'])} | "
            f"{n['positive_sessions']} |"
        )
    lines += [
        "",
        "## Per session, primary delay (1 minute)",
        "",
        "| session | tags | names | missing | median round trip (bps) | "
        + " | ".join(f"{s} IC | {s} gross | {s} net" for s in bb.SCORES)
        + " |",
        "|---|---|---:|---:|---:|" + "---:|---:|---:|" * len(bb.SCORES),
    ]
    for date, s in doc["sessions"].items():
        run = s["runs"]["1"]
        cells = []
        for sc in bb.SCORES:
            r = run["scores"][sc]
            cells += [
                _f(r["rank_ic"]["mean"], 4),
                _f(r["gross_bps_per_rebalance"]["mean"]),
                _f(r["net_bps_per_rebalance"]["mean"]),
            ]
        lines.append(
            f"| {date} | {', '.join(s['tags']) or '-'} | {s['names']} | {s['missing']} | "
            f"{_f(run['median_round_trip_cost_bps'])} | " + " | ".join(cells) + " |"
        )
    n = len(doc["sessions"])
    lines += [
        "",
        "## How to read it",
        "",
        f"- {n} sessions detect a net Sharpe of about {_f(doc['mde_sharpe'], 1)} or more"
        " (`docs/research/PNL_POWER_TABLE.md`). A null here rules out only a very large effect;",
        "  a positive here would be a reason to pre-register one look at the sealed 2025/26",
        "  sessions, not a result.",
        "- The universe was chosen on 2019-01-30, which is also one of the sessions. Later",
        "  sessions lose names that delisted or changed symbol (the `missing` column).",
        "- Costs: full turnover each rebalance, crossing one venue's quoted spread in and out.",
        "  No fee, impact or borrow.",
        "",
    ]
    return "\n".join(lines)


def main(argv: list[str] | None = None) -> int:
    ap = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    ap.add_argument("--bars-dir", type=Path, default=ROOT / "data" / "real" / "bars")
    ap.add_argument("--out-dir", type=Path, default=ROOT / "research" / "round1")
    args = ap.parse_args(argv)
    symbols = json.loads(UNIVERSE.read_text(encoding="utf-8"))["symbols"]
    files = session_files(args.bars_dir)
    if not files:
        print("no bars files")
        return 2
    sessions: dict = {}
    for date, path in files.items():
        panel = bb.load_panel(path)
        rows, missing = bb.rows_for(panel, symbols)
        runs = {str(d): bb.run_study(panel, rows, LOOKBACK, STEP, HORIZON, d) for d in DELAYS}
        for r in runs.values():
            for sc in r["scores"].values():
                sc.pop("per_rebalance")
        sessions[date] = {
            "tags": sorted(day_tags(date)),
            "names": len(rows),
            "missing": len(missing),
            "runs": runs,
        }
        print(f"{date}: {len(rows)} names, {len(missing)} missing", flush=True)
    pooled: dict = {}
    for d in DELAYS:
        for sc in bb.SCORES:
            per = [s["runs"][str(d)]["scores"][sc] for s in sessions.values()]
            pooled[f"{d}|{sc}"] = {
                "rank_ic": bb.pool_sessions([p["rank_ic"]["mean"] for p in per]),
                "gross_bps": bb.pool_sessions([p["gross_bps_per_rebalance"]["mean"] for p in per]),
                "net_bps": bb.pool_sessions([p["net_bps_per_rebalance"]["mean"] for p in per]),
            }
    n = len(sessions)
    doc = _clean(
        {
            "schema": "iap.round1.breadth_bars_pooled/1",
            "evidence_class": "exploratory",
            "universe_file": str(UNIVERSE.relative_to(ROOT)).replace("\\", "/"),
            "looks": n * len(DELAYS) * len(bb.SCORES),
            "sessions": sessions,
            "pooled": pooled,
            "mde_sharpe": mde_sharpe(n) if n >= 2 else math.nan,
        }
    )
    args.out_dir.mkdir(parents=True, exist_ok=True)
    (args.out_dir / "breadth_bars_pooled.json").write_text(
        json.dumps(doc, indent=1, sort_keys=True) + "\n", encoding="utf-8", newline="\n"
    )
    (args.out_dir / "BREADTH_BARS_POOLED.md").write_text(
        render(doc), encoding="utf-8", newline="\n"
    )
    print(render(doc))
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
