def _sha256_small(path: Path) -> str:
    return hashlib.sha256(path.read_bytes()).hexdigest()


def _book_check_summary(bc: dict | None) -> dict | None:
    """The ingest's own book check (``iap.marketdata.ingest`` ``_BookCheck``):
    ``clean`` plus the counters that decide it and the events applied per symbol."""
    if not isinstance(bc, dict):
        return None
    per = bc.get("per_symbol") or {}
    return {
        "clean": bc.get("clean"),
        "crossing_adds": bc.get("crossing_adds"),
        "crossed_on_resume": bc.get("crossed_on_resume"),
        "dropped": bc.get("dropped"),
        "symbols_checked": len(per),
        "events_applied": sum(int(v.get("events_applied") or 0) for v in per.values()),
        "crossed_at_end": sorted(k for k, v in per.items() if v.get("crossed_at_end")),
    }


def _book_verification_summary(bv) -> dict | None:
    """The source's independent answer, where one exists: IEX TOPS per symbol
    (``status`` match / mismatch, ``compared``, ``mismatched``) or a single
    LOBSTER-style book comparison report."""
    if not bv or not isinstance(bv, dict):
        return None
    if all(isinstance(v, dict) and "status" in v for v in bv.values()):
        statuses = sorted({str(v.get("status")) for v in bv.values()})
        return {
            "oracle": sorted({str(v.get("oracle")) for v in bv.values() if v.get("oracle")}),
            "symbols": len(bv),
            "statuses": statuses,
            "compared": sum(int(v.get("compared") or 0) for v in bv.values()),
            "mismatched": sum(int(v.get("mismatched") or 0) for v in bv.values()),
            "status": "match" if statuses == ["match"] else "mismatch",
        }
    ok = bv.get("match", bv.get("ok", bv.get("clean")))
    return {
        "oracle": ["book_file"],
        "symbols": 1,
        "statuses": ["match" if ok else "mismatch"],
        "compared": int(bv.get("compared", bv.get("rows", 0)) or 0),
        "mismatched": int(bv.get("mismatched", bv.get("mismatches", 0)) or 0),
        "status": "match" if ok else "mismatch",
    }


def session_verdict(book_check: dict | None, book_verification: dict | None) -> str:
    """One word per session.  ``none``: no committed book check (nothing to cite);
    ``mismatch``: the source's own answer disagrees; ``not clean``: the rebuilt book
    crossed or dropped; ``clean, match``: both pass; ``clean``: the book check passes
    and the source publishes no independent answer (ITCH has none)."""
    if not book_check or book_check.get("clean") is None:
        return "none"
    if book_verification is not None and book_verification.get("status") != "match":
        return "mismatch"
    if not book_check.get("clean"):
        return "not clean"
    return "clean, match" if book_verification is not None else "clean"


_VERDICT_RANK = {"none": 0, "mismatch": 1, "not clean": 2, "clean": 3, "clean, match": 4}


def dataset_verdict(session_verdicts: list[str]) -> str:
    """The weakest session verdict (``none`` for a dataset without sessions)."""
    if not session_verdicts:
        return "none"
    return min(session_verdicts, key=lambda v: _VERDICT_RANK.get(v, 0))


def _session_evidence(s: dict) -> dict:
    per = s.get("per_symbol") or {}
    bc = _book_check_summary(s.get("book_check"))
    bv = _book_verification_summary(s.get("book_verification"))
    msgs = s.get("messages") or {}
    return {
        "messages_total": msgs.get("total"),
        "skipped_unknown": msgs.get("skipped_unknown"),
        "symbols": len(per),
        "events": sum(int(v.get("events") or 0) for v in per.values()),
        "book_check": bc,
        "book_verification": bv,
        "verdict": session_verdict(bc, bv),
    }


def _evidence(doc: dict, sessions: dict[str, dict]) -> dict:
    """The D3 integrity record of one dataset, from ``dataset.json`` only."""
    norm = doc.get("normalized") or {}
    return {
        "decode": {
            "ingest_rules_version": doc.get("ingest_rules_version"),
            "qc_totals": norm.get("qc_totals"),
            "sessions": len(sessions),
            "messages_total": sum(int(e["messages_total"] or 0) for e in sessions.values()),
            "events": sum(int(e["events"]) for e in sessions.values()),
        },
        "hash": {
            "dataset_version": doc.get("dataset_version"),
            "over": "iap.real-dataset.v2 + name and sha256 of every normalized IAP1 file",
            "normalized_files": len(norm.get("files") or {}),
        },
        "sessions": sessions,
        "verdict": dataset_verdict([e["verdict"] for e in sessions.values()]),
    }


def _daily_entry(rel: str, ds_json: Path, doc: dict) -> dict:
    """A DD1 ingestion record (``kind: daily_pit``): partitions, hashes, counts,
    the test block; nothing read beyond ``dataset.json``."""
    parts = {}
    for name, p in sorted((doc.get("partitions") or {}).items()):
        parts[name] = {
            "location": p.get("location"),
            "dataset_hash_id": p.get("dataset_hash_id"),
            "files": p.get("files") or {},
            "row_counts": p.get("row_counts") or {},
            "chain_head": p.get("chain_head"),
            "refused": p.get("refused"),
        }
    tests = doc.get("dd1_tests") or {}
    status = doc.get("status") or "incomplete"
    return {
        "path": rel,
        "dataset_version": None,
        "kind": "daily_pit",
        "purchase_year": doc.get("purchase_year"),
        "sources": doc.get("sources"),
        "windows": doc.get("windows"),
        "dataset_json_sha256": _sha256_small(ds_json),
        "partitions": parts,
        "evidence": {
            "kind": "dd1_tests",
            "tests": {
                k: {kk: vv for kk, vv in v.items() if kk != "convention"}
                for k, v in (tests.get("results") or {}).items()
            },
            "open_close_convention": (tests.get("results") or {})
            .get("open_close_convention", {})
            .get("convention"),
            "thresholds": tests.get("thresholds"),
            "evidence_class": doc.get("evidence_class"),
            "verdict": status,
        },
    }


def _entry(root: Path, ds_json: Path) -> dict:
    doc = json.loads(ds_json.read_text(encoding="utf-8"))
    rel = ds_json.parent.relative_to(root).as_posix()
    if doc.get("kind") == "daily_pit":
        return _daily_entry(rel, ds_json, doc)
    own_status = SPEND_BY_PATH.get(rel)
    sessions = {}
    evidence_sessions = {}
    for date, s in sorted((doc.get("sessions") or {}).items()):
        evidence_sessions[date] = _session_evidence(s)
        sessions[date] = {
            "format": s.get("format"),
            "symbols": s.get("symbols"),
            "inputs": [
                {"file": i.get("file"), "sha256": i.get("sha256"), "bytes": i.get("bytes")}
                for i in s.get("inputs") or []
            ],
            "raw_sha256": (s.get("raw") or {}).get("sha256"),
            "status": own_status or SPEND_STATUS.get(date),
        }
    keep = ds_json.parent / "KEEP.json"
    oracle = _oracle_inputs(ds_json.parent / "process_report.json")
    src = doc.get("source") or {}
    return {
        "path": rel,
        "dataset_version": doc.get("dataset_version"),
        "kind": doc.get("kind"),
        "venue": src.get("venue"),
        "format": src.get("format"),
        "layout": doc.get("layout", "full"),
        "universe": doc.get("universe"),
        "config_version": doc.get("config_version"),
        "dataset_json_sha256": _sha256_small(ds_json),
        "keep_json_sha256": _sha256_small(keep) if keep.is_file() else None,
        "oracle_inputs": oracle,
        "normalized_files": (doc.get("normalized") or {}).get("files") or {},
        "sessions": sessions,
        "status": own_status,
        "evidence": _evidence(doc, evidence_sessions),
    }


def _oracle_inputs(report: Path) -> list[dict]:
    """The TOPS capture(s) a process-iex-day run verified the book against:
    recorded in its ``process_report.json``, not in ``dataset.json``."""
    if not report.is_file():
        return []
    doc = json.loads(report.read_text(encoding="utf-8"))
    out = []
    for step in doc.get("steps") or []:
        if step.get("step") == "download_tops" and step.get("sha256"):
            out.append({"feed": "TOPS", "sha256": step["sha256"], "bytes": step.get("bytes")})
    return out


def generate(data_root: Path) -> dict:
    """The manifest of every ``dataset.json`` under ``data_root`` (depth <= 3:
    ``<name>/dataset.json`` and ``<group>/<name>/dataset.json``)."""
    found = sorted(
        {*data_root.glob("*/dataset.json"), *data_root.glob("*/*/dataset.json")},
        key=lambda p: p.as_posix(),
    )
    datasets = [_entry(data_root, p) for p in found]
    return {
        "schema": SCHEMA,
        "note": "generated by tools/data_manifest.py from dataset.json files only; "
        "raw and normalized files are never read. CI checks preregs and ledgers "
        "against this list (the data itself is git-ignored). v2 (D3): 'evidence' per "
        "dataset copies the ingest's decode counts, book_check and book_verification "
        "with one verdict per session and per dataset; a cited dataset without a "
        "verdict fails check.",
        "datasets": datasets,
        "non_disk": [{"dataset_version": v, **meta} for v, meta in sorted(NON_DISK.items())],
    }


def listed_versions(manifest: dict) -> set[str]:
    out = {d["dataset_version"] for d in manifest.get("datasets", []) if d.get("dataset_version")}
    out |= {d["dataset_version"] for d in manifest.get("non_disk", [])}
    out |= set(partition_ids(manifest))
    return out


def partition_ids(manifest: dict) -> dict[str, tuple[str, str]]:
    """``dataset_hash_id -> (verdict, where)`` of every DD1 partition listed."""
    out: dict[str, tuple[str, str]] = {}
    for d in manifest.get("datasets", []):
        if d.get("kind") != "daily_pit":
            continue
        verdict = (d.get("evidence") or {}).get("verdict") or "incomplete"
        for name, p in (d.get("partitions") or {}).items():
            if p.get("dataset_hash_id"):
                out[p["dataset_hash_id"]] = (verdict, f"{d.get('path')}/{name}")
    return out


def listed_inputs(manifest: dict) -> set[str]:
    """sha256 of every raw vendor input recorded for a listed dataset. A study that
    reads the raw vendor file itself (e.g. REL-08c's NOII extraction from the
    full-market ITCH file) cites that file's sha256, which is covered when the
    file is a recorded input of a manifest-listed dataset."""
    out: set[str] = set()
    for d in manifest.get("datasets", []):
        for s in (
            (d.get("sessions") or {}).values()
            if isinstance(d.get("sessions"), dict)
            else d.get("sessions") or []
        ):
            for i in (s.get("inputs") or []) if isinstance(s, dict) else []:
                if i.get("sha256"):
                    out.add(i["sha256"])
        for i in d.get("inputs") or []:
            if isinstance(i, dict) and i.get("sha256"):
                out.add(i["sha256"])
    return out


def cited_files(repo: Path = ROOT) -> list[Path]:
    """Committed preregistrations and ledgers (``git ls-files research``)."""
    try:
        names = subprocess.check_output(
            ["git", "ls-files", "research"], cwd=repo, text=True
        ).split()
    except (OSError, subprocess.CalledProcessError):
        names = [p.relative_to(repo).as_posix() for p in (repo / "research").rglob("*.json")]
    return [repo / n for n in sorted(names) if _CITED.search(n)]


def cited_versions(doc, under_dataset_key: bool = False) -> set[str]:
    """Every 64-hex value (or dict key) inside a dataset-named key's value."""
    out: set[str] = set()
    if isinstance(doc, dict):
        for k, v in doc.items():
            hit = under_dataset_key or bool(_DATASET_KEY.search(str(k)))
            if under_dataset_key and _HEX64.fullmatch(str(k)):
                out.add(str(k))
            out |= cited_versions(v, hit)
    elif isinstance(doc, list):
        for v in doc:
            out |= cited_versions(v, under_dataset_key)
    elif isinstance(doc, str) and under_dataset_key:
        out |= set(_HEX64.findall(doc))
    return out


def verdicts(manifest: dict) -> dict[str, tuple[str, str]]:
    """``dataset_version -> (verdict, where)`` for every listed version (non-disk
    entries carry their own verdict string; a dataset without ``evidence`` is ``none``)."""
    out: dict[str, tuple[str, str]] = {}
    for d in manifest.get("datasets", []):
        if d.get("dataset_version"):
            verdict = (d.get("evidence") or {}).get("verdict") or "none"
            out[d["dataset_version"]] = (verdict, d.get("path") or "?")
    for d in manifest.get("non_disk", []):
        verdict = (d.get("evidence") or {}).get("verdict") or "none"
        out[d["dataset_version"]] = (verdict, d.get("kind") or "non-disk")
    out.update(partition_ids(manifest))
    return out


def _not_clean_counters(manifest: dict, version: str) -> dict:
    counters = dict.fromkeys(_COUNTERS, 0)
    for d in manifest.get("datasets", []):
        if d.get("dataset_version") != version:
            continue
        for e in ((d.get("evidence") or {}).get("sessions") or {}).values():
            bc = e.get("book_check") or {}
            for k in _COUNTERS:
                counters[k] += int(bc.get(k) or 0)
    return counters


def evidence_problems(manifest: dict, cited: set[str]) -> list[str]:
    """D3: every cited, listed version needs a verdict other than ``none`` or
    ``mismatch``; ``not clean`` passes only when acknowledged with the same counters."""
    problems = []
    by = verdicts(manifest)
    for v in sorted(cited):
        if v not in by:
            continue  # an unlisted citation is reported by check() itself
        verdict, where = by[v]
        if verdict in ("none", "mismatch", "incomplete"):
            problems.append(
                f"cited dataset {v} ({where}) has verdict {verdict!r}: no clean/match evidence"
            )
        elif verdict == "not clean":
            ack = NOT_CLEAN_ACKNOWLEDGED.get(v)
            have = _not_clean_counters(manifest, v)
            if ack is None:
                problems.append(
                    f"cited dataset {v} ({where}) is 'not clean' ({have}) and not acknowledged "
                    "(tools/data_manifest.py NOT_CLEAN_ACKNOWLEDGED, defect register)"
                )
            elif any(have[k] != ack.get(k) for k in _COUNTERS):
                want = {k: ack.get(k) for k in _COUNTERS}
                problems.append(
                    f"cited dataset {v} ({where}) is 'not clean' with counters {have}, "
                    f"acknowledged for {want}"
                )
    return problems


def check(manifest_path: Path, repo: Path = ROOT, data_root: Path | None = None) -> list[str]:
    """Problems (empty = pass)."""
    if not manifest_path.is_file():
        return [f"{manifest_path} is missing: run tools/data_manifest.py generate"]
    manifest = json.loads(manifest_path.read_text(encoding="utf-8"))
    problems = []
    if manifest.get("schema") != SCHEMA:
        problems.append(f"{manifest_path.name}: schema {manifest.get('schema')!r} != {SCHEMA}")
    listed = listed_versions(manifest) | listed_inputs(manifest)
    cited_all: set[str] = set()
    for f in cited_files(repo):
        try:
            doc = json.loads(f.read_text(encoding="utf-8"))
        except (OSError, json.JSONDecodeError) as exc:
            problems.append(f"{f.relative_to(repo).as_posix()}: unreadable ({exc})")
            continue
        cited = cited_versions(doc)
        cited_all |= cited
        for v in sorted(cited - listed):
            problems.append(f"{f.relative_to(repo).as_posix()} cites unlisted dataset {v}")
    problems += evidence_problems(manifest, cited_all)
    if data_root is not None:
        fresh = generate(data_root)
        if fresh != manifest:
            problems.append(
                f"{manifest_path.name} is stale against {data_root}: run "
                "tools/data_manifest.py generate"
            )
    return problems


def _write(doc: dict, out: Path) -> None:
    out.parent.mkdir(parents=True, exist_ok=True)
    with open(out, "w", encoding="utf-8", newline="\n") as f:
        f.write(json.dumps(doc, indent=2, sort_keys=False) + "\n")


def main(argv: list[str] | None = None) -> int:
    p = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    sub = p.add_subparsers(dest="cmd", required=True)
    g = sub.add_parser("generate", help="write the manifest from a data root")
    g.add_argument("--data-root", default=str(DEFAULT_DATA_ROOT))
    g.add_argument("--out", default=str(DEFAULT_OUT))
    c = sub.add_parser("check", help="preregs / ledgers cite only listed versions")
    c.add_argument("--manifest", default=str(DEFAULT_OUT))
    c.add_argument("--data-root", default=None, help="also require the manifest to be fresh")
    a = p.parse_args(argv)
    if a.cmd == "generate":
        root = Path(a.data_root)
        if not root.is_dir():
            print(f"no data root at {root}", file=sys.stderr)
            return 2
        doc = generate(root)
        _write(doc, Path(a.out))
        print(f"{a.out}: {len(doc['datasets'])} datasets, {len(doc['non_disk'])} non-disk")
        return 0
    problems = check(Path(a.manifest), ROOT, Path(a.data_root) if a.data_root else None)
    for line in problems:
        print(f"data-manifest: {line}", file=sys.stderr)
    if not problems:
        print("data-manifest: every cited dataset version is listed and carries a verdict")
    return 1 if problems else 0


if __name__ == "__main__":
    raise SystemExit(main())
