#!/usr/bin/env python3
"""Data manifest (v1.18 REL-12): every dataset the research record may cite.

``generate`` walks a data root (default ``data/real``, git-ignored) for every
``dataset.json`` and writes ``research/data_manifest.json``: per dataset the
path relative to the root, ``dataset_version``, kind / venue / format, its
sessions with every vendor input's file name, sha256 and bytes (as recorded
at ingest: the large raw and normalized files are never opened or hashed
here), the normalized-file hashes the ingest recorded, the TOPS oracle
capture a ``process_report.json`` records, the sha256 of
``KEEP.json`` when a processed-and-deleted day kept one, and the purpose /
spend status of its sessions where the v1.18 baseline records it
(:data:`SPEND_STATUS`, from research/v118/BASELINE_v1_18.md §2).  Versions
that are cited but have no dataset on disk — the synthetic dataset of the
committed generator config and the pre-scope ledger placeholder — are listed
with their provenance in :data:`NON_DISK`.

``check`` is the CI gate: the real data is not in git, so the committed
manifest is the list.  Every 64-hex value under a key naming a dataset
(``dataset_version``, ``nasdaq_dataset_version``, ``dataset_versions`` …,
dict keys included) in the preregistrations and ledgers
(:func:`cited_files`) must be a listed version; ``check --data-root`` also
proves the committed manifest equals a fresh generation from that root.

    python tools/data_manifest.py generate --data-root data/real
    python tools/data_manifest.py check                  # CI
    python tools/data_manifest.py check --data-root data/real   # locally: also stale?
"""

from __future__ import annotations

import argparse
import hashlib
import json
import re
import subprocess
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
DEFAULT_OUT = ROOT / "research" / "data_manifest.json"
DEFAULT_DATA_ROOT = ROOT / "data" / "real"
SCHEMA = "iap.data_manifest/v1"

_HEX64 = re.compile(r"\b[0-9a-f]{64}\b")
_DATASET_KEY = re.compile(r"dataset|data_version", re.IGNORECASE)
_CITED = re.compile(r"(prereg|ledger)[^/]*\.json$|^research/experiments\.json$", re.IGNORECASE)

#: Cited versions with no dataset directory: provenance, not a disk read.
NON_DISK: dict[str, dict] = {
    "116b77873de422ddd3b4f875625a0d8bba7dc2850068aae6ed807e944fb34573": {
        "kind": "synthetic",
        "provenance": "the generator's committed config (v1.4.0; configs/strategies/"
        "alpha_params.json data_version, docs/runbooks/RUNBOOK_data_pipeline.md); "
        "regenerated by `iap.marketdata generate`, never downloaded",
    },
    "203c8f540f75de984fa80f5ec9c04a91a1252819586a9fca6d48483f1462e67b": {
        "kind": "legacy-placeholder",
        "provenance": "research/migrate_ledger_dataset_scope.py LEGACY_DATASET_VERSION: "
        "ledger entries recorded before per-dataset scoping (synthetic per the v1.18 baseline)",
    },
}

#: Purpose / spend of session dates, from the v1.18 baseline's "data already
#: examined" table (research/v118/BASELINE_v1_18.md §2; audit, not
#: recomputed).  The REL-02 holdout registry is the enforced state; this is
#: only the record it starts from.  Dates not listed have no recorded status.
_SPEND_ROWS = (
    (
        ("2019-01-30", "2019-03-27", "2019-07-30", "2019-08-30", "2019-10-30", "2019-12-30",
         "2020-01-30"),
        "multi7 in-sample: all EQ alphas, net-of-cost screen, breadth book, B7",
        "in-sample, spent",
    ),
    (
        ("2019-10-18", "2021-07-13", "2021-08-13"),
        "v1.16 monetisation, AI4 train and validation",
        "in-sample",
    ),
    (
        ("2025-11-28", "2025-12-08", "2025-12-09", "2025-12-10", "2025-12-11", "2025-12-12",
         "2026-06-12"),
        "R7 confirm (one look each of EQ10 and EQ05); B8 calibration and evaluation",
        "holdout read once, then reused",
    ),
    (
        ("2026-05-15", "2026-05-18"),
        "v1.8 holdout (6 alphas, 504 looks), AUC01, B8 evaluation",
        "spent three times",
    ),
)  # fmt: skip
SPEND_STATUS: dict[str, dict[str, str]] = {
    d: {"purpose": purpose, "spend": spend} for dates, purpose, spend in _SPEND_ROWS for d in dates
}
#: Dataset directories with a status of their own (not by date).
SPEND_BY_PATH = {
    "breadth/ds_20190130": {"purpose": "breadth (100 names)", "spend": "features built, never read"}
}


def _sha256_small(path: Path) -> str:
    return hashlib.sha256(path.read_bytes()).hexdigest()


def _entry(root: Path, ds_json: Path) -> dict:
    doc = json.loads(ds_json.read_text(encoding="utf-8"))
    rel = ds_json.parent.relative_to(root).as_posix()
    own_status = SPEND_BY_PATH.get(rel)
    sessions = {}
    for date, s in sorted((doc.get("sessions") or {}).items()):
        sessions[date] = {
            "format": s.get("format"),
            "symbols": s.get("symbols"),
            "inputs": [
                {"file": i.get("file"), "sha256": i.get("sha256"), "bytes": i.get("bytes")}
                for i in s.get("inputs") or []
            ],
            "raw_sha256": (s.get("raw") or {}).get("sha256"),
            "status": own_status or SPEND_STATUS.get(date),
        }
    keep = ds_json.parent / "KEEP.json"
    oracle = _oracle_inputs(ds_json.parent / "process_report.json")
    src = doc.get("source") or {}
    return {
        "path": rel,
        "dataset_version": doc.get("dataset_version"),
        "kind": doc.get("kind"),
        "venue": src.get("venue"),
        "format": src.get("format"),
        "layout": doc.get("layout", "full"),
        "universe": doc.get("universe"),
        "config_version": doc.get("config_version"),
        "dataset_json_sha256": _sha256_small(ds_json),
        "keep_json_sha256": _sha256_small(keep) if keep.is_file() else None,
        "oracle_inputs": oracle,
        "normalized_files": (doc.get("normalized") or {}).get("files") or {},
        "sessions": sessions,
        "status": own_status,
    }


def _oracle_inputs(report: Path) -> list[dict]:
    """The TOPS capture(s) a process-iex-day run verified the book against:
    recorded in its ``process_report.json``, not in ``dataset.json``."""
    if not report.is_file():
        return []
    doc = json.loads(report.read_text(encoding="utf-8"))
    out = []
    for step in doc.get("steps") or []:
        if step.get("step") == "download_tops" and step.get("sha256"):
            out.append({"feed": "TOPS", "sha256": step["sha256"], "bytes": step.get("bytes")})
    return out


def generate(data_root: Path) -> dict:
    """The manifest of every ``dataset.json`` under ``data_root`` (depth <= 3:
    ``<name>/dataset.json`` and ``<group>/<name>/dataset.json``)."""
    found = sorted(
        {*data_root.glob("*/dataset.json"), *data_root.glob("*/*/dataset.json")},
        key=lambda p: p.as_posix(),
    )
    datasets = [_entry(data_root, p) for p in found]
    return {
        "schema": SCHEMA,
        "note": "generated by tools/data_manifest.py from dataset.json files only; "
        "raw and normalized files are never read. CI checks preregs and ledgers "
        "against this list (the data itself is git-ignored).",
        "datasets": datasets,
        "non_disk": [{"dataset_version": v, **meta} for v, meta in sorted(NON_DISK.items())],
    }


def listed_versions(manifest: dict) -> set[str]:
    out = {d["dataset_version"] for d in manifest.get("datasets", []) if d.get("dataset_version")}
    out |= {d["dataset_version"] for d in manifest.get("non_disk", [])}
    return out


def listed_inputs(manifest: dict) -> set[str]:
    """sha256 of every raw vendor input recorded for a listed dataset. A study that
    reads the raw vendor file itself (e.g. REL-08c's NOII extraction from the
    full-market ITCH file) cites that file's sha256, which is covered when the
    file is a recorded input of a manifest-listed dataset."""
    out: set[str] = set()
    for d in manifest.get("datasets", []):
        for s in (
            (d.get("sessions") or {}).values()
            if isinstance(d.get("sessions"), dict)
            else d.get("sessions") or []
        ):
            for i in (s.get("inputs") or []) if isinstance(s, dict) else []:
                if i.get("sha256"):
                    out.add(i["sha256"])
        for i in d.get("inputs") or []:
            if isinstance(i, dict) and i.get("sha256"):
                out.add(i["sha256"])
    return out


def cited_files(repo: Path = ROOT) -> list[Path]:
    """Committed preregistrations and ledgers (``git ls-files research``)."""
    try:
        names = subprocess.check_output(
            ["git", "ls-files", "research"], cwd=repo, text=True
        ).split()
    except (OSError, subprocess.CalledProcessError):
        names = [p.relative_to(repo).as_posix() for p in (repo / "research").rglob("*.json")]
    return [repo / n for n in sorted(names) if _CITED.search(n)]


def cited_versions(doc, under_dataset_key: bool = False) -> set[str]:
    """Every 64-hex value (or dict key) inside a dataset-named key's value."""
    out: set[str] = set()
    if isinstance(doc, dict):
        for k, v in doc.items():
            hit = under_dataset_key or bool(_DATASET_KEY.search(str(k)))
            if under_dataset_key and _HEX64.fullmatch(str(k)):
                out.add(str(k))
            out |= cited_versions(v, hit)
    elif isinstance(doc, list):
        for v in doc:
            out |= cited_versions(v, under_dataset_key)
    elif isinstance(doc, str) and under_dataset_key:
        out |= set(_HEX64.findall(doc))
    return out


def check(manifest_path: Path, repo: Path = ROOT, data_root: Path | None = None) -> list[str]:
    """Problems (empty = pass)."""
    if not manifest_path.is_file():
        return [f"{manifest_path} is missing: run tools/data_manifest.py generate"]
    manifest = json.loads(manifest_path.read_text(encoding="utf-8"))
    problems = []
    if manifest.get("schema") != SCHEMA:
        problems.append(f"{manifest_path.name}: schema {manifest.get('schema')!r} != {SCHEMA}")
    listed = listed_versions(manifest) | listed_inputs(manifest)
    for f in cited_files(repo):
        try:
            doc = json.loads(f.read_text(encoding="utf-8"))
        except (OSError, json.JSONDecodeError) as exc:
            problems.append(f"{f.relative_to(repo).as_posix()}: unreadable ({exc})")
            continue
        for v in sorted(cited_versions(doc) - listed):
            problems.append(f"{f.relative_to(repo).as_posix()} cites unlisted dataset {v}")
    if data_root is not None:
        fresh = generate(data_root)
        if fresh != manifest:
            problems.append(
                f"{manifest_path.name} is stale against {data_root}: run "
                "tools/data_manifest.py generate"
            )
    return problems


def _write(doc: dict, out: Path) -> None:
    out.parent.mkdir(parents=True, exist_ok=True)
    with open(out, "w", encoding="utf-8", newline="\n") as f:
        f.write(json.dumps(doc, indent=2, sort_keys=False) + "\n")


def main(argv: list[str] | None = None) -> int:
    p = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    sub = p.add_subparsers(dest="cmd", required=True)
    g = sub.add_parser("generate", help="write the manifest from a data root")
    g.add_argument("--data-root", default=str(DEFAULT_DATA_ROOT))
    g.add_argument("--out", default=str(DEFAULT_OUT))
    c = sub.add_parser("check", help="preregs / ledgers cite only listed versions")
    c.add_argument("--manifest", default=str(DEFAULT_OUT))
    c.add_argument("--data-root", default=None, help="also require the manifest to be fresh")
    a = p.parse_args(argv)
    if a.cmd == "generate":
        root = Path(a.data_root)
        if not root.is_dir():
            print(f"no data root at {root}", file=sys.stderr)
            return 2
        doc = generate(root)
        _write(doc, Path(a.out))
        print(f"{a.out}: {len(doc['datasets'])} datasets, {len(doc['non_disk'])} non-disk")
        return 0
    problems = check(Path(a.manifest), ROOT, Path(a.data_root) if a.data_root else None)
    for line in problems:
        print(f"data-manifest: {line}", file=sys.stderr)
    if not problems:
        print("data-manifest: every cited dataset version is listed")
    return 1 if problems else 0


if __name__ == "__main__":
    raise SystemExit(main())
