#!/usr/bin/env python3
"""Data manifest (v1.18 REL-12): every dataset the research record may cite.

``generate`` walks a data root (default ``data/real``, git-ignored) for every
``dataset.json`` and writes ``research/data_manifest.json``: per dataset the
path relative to the root, ``dataset_version``, kind / venue / format, its
sessions with every vendor input's file name, sha256 and bytes (as recorded
at ingest: the large raw and normalized files are never opened or hashed
here), the normalized-file hashes the ingest recorded, the TOPS oracle
capture a ``process_report.json`` records, the sha256 of
``KEEP.json`` when a processed-and-deleted day kept one, and the purpose /
spend status of its sessions where the v1.18 baseline records it
(:data:`SPEND_STATUS`, from research/v118/BASELINE_v1_18.md §2).  Versions
that are cited but have no dataset on disk — the synthetic dataset of the
committed generator config and the pre-scope ledger placeholder — are listed
with their provenance in :data:`NON_DISK`.

v2.0 stage 2 D3 (defect D-05): every entry also carries ``evidence``, the
integrity record copied from ``dataset.json``: the decode check (QC totals,
message and normalized-event counts per session), the content hash
(``dataset_version`` over the normalized IAP1 files), the ingest's
``book_check`` (a book rebuilt from the session's own orders: clean when no
displayed order crossed and nothing was dropped) and, where the source
publishes an independent answer, the ``book_verification`` against it (IEX
TOPS top-of-book oracle; LOBSTER book file).  :func:`session_verdict` reduces
them to one word per session and :func:`dataset_verdict` to one per dataset
(``clean, match`` / ``clean`` / ``not clean`` / ``mismatch`` / ``none``).
Nothing here reads a session's data: ``dataset.json`` is metadata.

v2.0 stage 2 DD1: a daily-route ingestion record (``kind: daily_pit``, written
by ``tools/ingest/dd1_daily.py`` as ``iap-runner`` under the development-readable
root) is listed as one entry with its four partitions: per partition the
``dataset_hash_id`` (the sealed service's content hash over the file set), the
file hashes and the row counts.  For the sealed partitions (Track B, Track C)
those come from the sealed service's ``ingest`` response, which recorded the
ingestion job's own counts; the development identity never recomputes them
(U0 section 2: no summary statistic of a sealed partition).  The entry's
``evidence`` is the DD1 test block (pass/fail counts) and its verdict is the
record's ``status`` (``complete`` / ``incomplete``); a cited partition of an
incomplete ingestion fails ``check``.

``check`` is the CI gate: the real data is not in git, so the committed
manifest is the list.  Every 64-hex value under a key naming a dataset
(``dataset_version``, ``nasdaq_dataset_version``, ``dataset_versions`` …,
dict keys included) in the preregistrations and ledgers
(:func:`cited_files`) must be a listed version **with a verdict**: a cited
dataset whose verdict is ``none`` (no committed book check) or ``mismatch``
fails, and so does a cited ``not clean`` dataset unless its version is in
:data:`NOT_CLEAN_ACKNOWLEDGED` with the counters it was acknowledged with
(the register row names it; the acknowledgement is a disclosed limitation,
never a cleared verdict).  ``check --data-root`` also proves the committed
manifest equals a fresh generation from that root.

    python tools/data_manifest.py generate --data-root data/real
    python tools/data_manifest.py check                  # CI
    python tools/data_manifest.py check --data-root data/real   # locally: also stale?
"""

