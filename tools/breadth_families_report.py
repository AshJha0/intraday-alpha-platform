#!/usr/bin/env python3
"""Render research/round1/BREADTH_FAMILIES.md from breadth_families.json and
breadth_bars_pooled.json, and apply the holdout selection rule of
FAMILIES_PRESPEC_2026-11-18.md section 5.  Reads no market data.

    python tools/breadth_families_report.py [--check]
"""

from __future__ import annotations

import argparse
import json
import math
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT / "python" / "src"))

from iap.research.breadth_bars import pool_sessions  # noqa: E402

R1 = ROOT / "research" / "round1"
OUT = R1 / "BREADTH_FAMILIES.md"
MIN_POSITIVE = 7
FAMILIES = {
    "momentum_30_d1": "F1 momentum, 30 minutes",
    "open_reversal_d1": "F2 opening reversal",
    "closing_imbalance_d1": "F3 closing-auction imbalance, version 2",
}
REVERSALS = {
    "1|vwap_deviation": "reversal, VWAP deviation, 15 minutes",
    "1|residual_reversion": "reversal, residual, 15 minutes",
}


def _f(v, nd=2) -> str:
    return "n/a" if v is None or not math.isfinite(v) else f"{v:.{nd}f}"


def candidates(fam: dict, pooled: dict) -> list[dict]:
    """One row per candidate of the selection rule, with its diagnostics."""
    rows = []
    for key, label in FAMILIES.items():
        per = [s[key] for s in fam["sessions"].values()]
        rows.append(
            {
                "label": label,
                "net": fam["pooled"][key],
                "ic": pool_sessions([p["rank_ic"]["mean"] or math.nan for p in per]),
                "gross": pool_sessions(
                    [
                        math.nan
                        if p["gross_bps_per_rebalance"]["mean"] is None
                        else p["gross_bps_per_rebalance"]["mean"]
                        for p in per
                    ]
                ),
            }
        )
    for key, label in REVERSALS.items():
        p = pooled["pooled"][key]
        rows.append(
            {"label": label, "net": p["net_bps"], "ic": p["rank_ic"], "gross": p["gross_bps"]}
        )
    return rows


def qualifies(net: dict, threshold: float) -> bool:
    return (
        net.get("mean") is not None
        and net["mean"] > 0
        and net["p_one_sided"] < threshold
        and net["positive_sessions"] >= MIN_POSITIVE
    )


def render(fam: dict, pooled: dict) -> str:
    thr = fam["one_sided_threshold"]
    rows = candidates(fam, pooled)
    passed = [r["label"] for r in rows if qualifies(r["net"], thr)]
    lines = [
        "# Bar families on ten in-sample sessions: results and the holdout rule",
        "",
        "Generated by `tools/breadth_families_report.py` from `breadth_families.json` and",
        "`breadth_bars_pooled.json`; rerun it, do not edit by hand. Exploratory, in-sample, no",
        "edge claim. Definitions and the rule: `FAMILIES_PRESPEC_2026-11-18.md`.",
        "",
        "**The plain idea.** One number per session per family: the mean net return of the decile",
        "book per rebalance, after crossing the quoted spread. The test is across the ten sessions.",
        "",
        f"Registered primaries: K = {fam['bonferroni_k']}; one-sided threshold {thr:g}.",
        "",
        "| candidate | sessions | net bps | net t | one-sided p | sessions net > 0 | gross bps | "
        "gross t | rank IC | IC t | sessions IC > 0 |",
        "|---|---:|---:|---:|---:|---:|---:|---:|---:|---:|---:|",
    ]
    for r in rows:
        n, g, ic = r["net"], r["gross"], r["ic"]
        lines.append(
            f"| {r['label']} | {n['n']} | {_f(n['mean'])} | {_f(n['t'])} | {_f(n['p_one_sided'], 4)} "
            f"| {n['positive_sessions']} | {_f(g['mean'])} | {_f(g['t'])} | {_f(ic['mean'], 4)} | "
            f"{_f(ic['t'])} | {ic['positive_sessions']} |"
        )
    lines += [
        "",
        "Gross and rank IC are declared diagnostics, not tests: they cannot promote a family.",
        "",
        "## Reading",
        "",
        "- No candidate has a positive net return that clears its threshold. Four of the five",
        "  lose several basis points per rebalance after the spread.",
        "- The closing-auction imbalance is the one family with a clear effect before costs: its",
        "  gross return and its rank IC are positive in every session. After the half spread paid",
        "  at the 15:56 quote the net is about zero. It assumes a full fill at the cross price,",
        "  which is an upper bound on what was tradable (`FAMILIES_PRESPEC`, section 3).",
        "- Ten sessions detect only a very large net Sharpe (`docs/research/PNL_POWER_TABLE.md`).",
        "  These results say what the spread costs against each gross effect; they do not rule",
        "  out a small net effect, and they confirm none.",
        "- F3 version 1 had no score on any session (specification error and dissemination",
        "  start); see the erratum in the pre-specification.",
        "",
        "## The holdout selection rule (section 5), applied",
        "",
        f"A candidate qualifies with a positive mean net, a one-sided p below {thr:g} and at least",
        f"{MIN_POSITIVE} of 10 sessions positive.",
        "",
        (
            "**Qualifying: " + ", ".join(passed) + ".**"
            if passed
            else "**None qualifies. Nothing goes forward and the nine-session holdout stays sealed.**"
        ),
        "",
    ]
    return "\n".join(lines)


def main(argv: list[str] | None = None) -> int:
    ap = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    ap.add_argument("--check", action="store_true")
    args = ap.parse_args(argv)
    fam = json.loads((R1 / "breadth_families.json").read_text(encoding="utf-8"))
    pooled = json.loads((R1 / "breadth_bars_pooled.json").read_text(encoding="utf-8"))
    text = render(fam, pooled)
    if args.check:
        ok = OUT.is_file() and OUT.read_text(encoding="utf-8") == text
        print("current" if ok else "stale: research/round1/BREADTH_FAMILIES.md")
        return 0 if ok else 1
    OUT.write_text(text, encoding="utf-8", newline="\n")
    print(text)
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
