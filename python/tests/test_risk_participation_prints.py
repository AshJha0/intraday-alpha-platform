"""v1.15 X-P1-3: the participation cap (check 27) against TRADE prints.

Golden: tests/golden/expected_risk_participation_prints.json (+ _audit.jsonl),
generated by python/tools/make_golden_risk_prints.py and replayed by Rust
(rust/risk/tests/golden_risk.rs). Only a TRADE print adds market volume.
"""

from __future__ import annotations

import json
from pathlib import Path

import pytest
from iap.risk import RiskEngine, instrument_refs_from_golden
from iap.risk.engine import TAPE_EVENT_TYPE
from test_risk_golden import replay_edge

REPO = Path(__file__).resolve().parents[2]
GOLDEN = REPO / "tests" / "golden" / "expected_risk_participation_prints.json"
AUDIT = REPO / "tests" / "golden" / "expected_risk_participation_prints_audit.jsonl"


@pytest.fixture(scope="module")
def golden() -> dict:
    return json.loads(GOLDEN.read_text(encoding="utf-8"))


@pytest.fixture(scope="module")
def config(golden) -> dict:
    return json.loads((REPO / golden["config"]).read_text(encoding="utf-8"))


def test_decisions_and_audit_match(golden, config):
    assert golden["x-version"] == 1
    audit = replay_edge(golden, config, check=True)
    assert audit.encode("utf-8") == AUDIT.read_bytes()
    for rule, frag in golden["must_pin"]:
        key = f'"rule_id":"{rule}"'
        assert any(key in line and frag in line for line in audit.splitlines()), (rule, frag)


def test_breaches_only_because_execute_is_not_volume(golden, config):
    """Counting EXECUTE as volume too doubles the cap: the first pinned
    breach (300 vs a 200 cap) would pass, so the golden tests the tape."""
    doubled = json.loads(json.dumps(golden))
    doubled["scenarios"] = [s for s in doubled["scenarios"] if s["name"] == "prints_only_count"]
    steps = doubled["scenarios"][0]["steps"]
    for st in steps:
        if st["type"] == "tape" and st["event_type"] == 4:
            st["event_type"] = TAPE_EVENT_TYPE
    replay_edge(doubled, config, check=False, fill_expect=True)
    got = {s["order"]["order_id"]: s["expect"]["rule_id"] for s in steps if s["type"] == "order"}
    assert got[1] == "ALLOW"


def test_non_trade_events_move_no_volume(golden):
    eng = RiskEngine.from_config(
        json.loads((REPO / golden["config"]).read_text(encoding="utf-8")),
        instrument_refs_from_golden(golden["instruments"]),
    )
    for et in range(0, 10):
        eng.on_market_event(1, et, 100, 1)
    assert eng._market_volume == {1: 100}
    with pytest.raises(ValueError):
        eng.on_market_event(1, 256, 100, 1)
