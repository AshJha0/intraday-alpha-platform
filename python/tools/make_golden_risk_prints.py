#!/usr/bin/env python3
"""Generate the participation-vs-tape golden (v1.15 X-P1-3):
``tests/golden/expected_risk_participation_prints.json`` and
``tests/golden/expected_risk_participation_prints_audit.jsonl``.

The SEC 15c3-5 participation cap (check 27) is a share of SESSION MARKET
VOLUME. The volume comes from the market-data stream through
``RiskEngine.on_market_event``: only TRADE prints (event type 5) count; an
EXECUTE (4) is the same trade seen from the book, so counting both doubles
the tape and loosens the cap 2x. Each scenario feeds ``tape`` steps (one
canonical market event each) and orders; the pinned orders breach the cap
only because the volume is the real print volume (they would pass if the
EXECUTE messages were counted too). Same format and driver as the edge
golden (``make_golden_risk_edge.py``); replayed by Python
(``python/tests/test_risk_participation_prints.py``) and Rust
(``rust/risk/tests/golden_risk.rs``). C++ has no risk engine.

Usage (from the repo root)::

    PYTHONPATH=python/src python python/tools/make_golden_risk_prints.py
"""

from __future__ import annotations

import json
import sys
from pathlib import Path
from typing import Any

ROOT = Path(__file__).resolve().parents[2]
sys.path.insert(0, str(ROOT / "python" / "src"))
sys.path.insert(0, str(ROOT / "python" / "tests"))
sys.path.insert(0, str(ROOT / "python" / "tools"))

from make_golden_risk_edge import SEC, T0, market, order  # noqa: E402
from test_risk_golden import replay_edge  # noqa: E402

ADD, MODIFY, CANCEL, EXECUTE, TRADE, QUOTE = 1, 2, 3, 4, 5, 6

DESCRIPTION = (
    "Participation-vs-tape golden (v1.15 X-P1-3), generated by "
    "python/tools/make_golden_risk_prints.py. Format and driver as "
    "expected_risk_edge_decisions.json, plus the step type tape "
    "(RiskEngine.on_market_event(instrument_id, event_type, qty, ts)): only a "
    "TRADE print (event_type 5) adds to the session market volume behind the "
    "participation cap (check 27); EXECUTE (4) and every other type are ignored. "
    "Pinned orders breach the cap only because the volume is the real print "
    "volume. Replayed by Python and Rust; the audit JSONL must match byte for byte."
)

PARTICIPATION = [
    ["pre_trade", "max_participation_bps", 1000.0],
    ["pre_trade", "participation_floor_qty", 100],
]


def tape(event_type: int, qty: int, ts: int, iid: int = 1) -> dict[str, Any]:
    return {"type": "tape", "instrument_id": iid, "event_type": event_type, "qty": qty, "ts": ts}


def scenarios() -> list[dict[str, Any]]:
    t = T0
    return [
        {
            "name": "prints_only_count",
            "config_set": PARTICIPATION,
            "steps": [
                market(1, 2450, 2452, t),
                # one 2,000-share trade, reported by the book (EXECUTE) and
                # the tape (TRADE): volume 2,000, cap 10% = 200 (4,000 / 400
                # if EXECUTE were counted too)
                tape(ADD, 5_000, t + SEC),
                tape(EXECUTE, 2_000, t + SEC),
                tape(TRADE, 2_000, t + SEC),
                tape(QUOTE, 9_000, t + SEC),
                order(1, 1, 0, 300, 2450, t + 2 * SEC, strategy="S1"),  # PARTICIPATION
                order(2, 1, 0, 150, 2450, t + 2 * SEC, strategy="S2"),  # ALLOW (150/200)
                order(3, 1, 0, 100, 2450, t + 3 * SEC, strategy="S3"),  # PARTICIPATION
                tape(EXECUTE, 1_000, t + 4 * SEC),
                tape(TRADE, 1_000, t + 4 * SEC),  # volume 3,000, cap 300
                tape(TRADE, 0, t + 4 * SEC),  # empty print: dropped
                tape(TRADE, 50_000, t + 4 * SEC, iid=9),  # unknown instrument: dropped
                order(4, 1, 0, 100, 2450, t + 5 * SEC, strategy="S3"),  # ALLOW (250/300)
                order(5, 1, 1, 100, 2452, t + 5 * SEC, strategy="S4"),  # PARTICIPATION
            ],
        },
        {
            "name": "no_prints_floor_only",
            "config_set": PARTICIPATION,
            "steps": [
                market(1, 2450, 2452, t),
                # book activity but no tape: the cap is the floor (100)
                tape(EXECUTE, 50_000, t + SEC),
                tape(MODIFY, 1_000, t + SEC),
                tape(CANCEL, 1_000, t + SEC),
                order(1, 1, 0, 150, 2450, t + 2 * SEC),  # PARTICIPATION
                order(2, 1, 0, 100, 2450, t + 2 * SEC),  # ALLOW (floor)
            ],
        },
    ]


MUST_PIN = [
    ["PARTICIPATION", "exceeds participation cap 200 (1000.0bps of market volume 2000"],
    ["PARTICIPATION", "of market volume 3000"],
    ["PARTICIPATION", "of market volume 0, floor 100"],
]


def main() -> None:
    golden: dict[str, Any] = {
        "x-version": 1,
        "description": DESCRIPTION,
        "config": "configs/risk/risk.json",
        "instruments": {"1": {"tick_size": 0.01, "qty_unit": 1.0, "quote_ccy": "USD"}},
        "must_pin": MUST_PIN,
        "scenarios": scenarios(),
    }
    with open(ROOT / golden["config"], encoding="utf-8") as f:
        config = json.load(f)
    audit = replay_edge(golden, config, check=False, fill_expect=True)
    for rule, frag in MUST_PIN:
        key = f'"rule_id":"{rule}"'
        if not any(key in line and frag in line for line in audit.splitlines()):
            raise SystemExit(f"must_pin not reached: {rule} / {frag}")
    out = ROOT / "tests" / "golden"
    with open(
        out / "expected_risk_participation_prints.json", "w", encoding="utf-8", newline="\n"
    ) as f:
        f.write(json.dumps(golden, indent=2) + "\n")
    with open(
        out / "expected_risk_participation_prints_audit.jsonl", "w", encoding="utf-8", newline="\n"
    ) as f:
        f.write(audit)
    n = sum(1 for sc in golden["scenarios"] for s in sc["steps"] if s["type"] == "order")
    print(f"{len(golden['scenarios'])} scenarios, {n} orders, {len(audit.splitlines())} lines")


if __name__ == "__main__":
    main()
