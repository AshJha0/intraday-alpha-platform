#!/usr/bin/env python3
"""Generate ``tests/golden/expected_venue_queue.json`` (x-version 1): the
rule-4 queue-position golden of the Rust venue simulator (v1.17 B9).

The Python execution simulator (``iap.execution.simulator``, the reference
for execution simulator rule 4, API_TRADING.md section 2) is driven through
a handful of fixed, hand-designed vectors with ZERO latency (internal legs 0,
venue leg 0, no jitter): an order submitted after the event with ``event_id``
k (``after_event``) activates before the next event against the book event k
left, which is exactly the
state the Rust ``SimulatedVenue`` sees when ``submit`` is called between the
two events. Every fill the Python simulator emits (order, event time,
quantity, price, liquidity) and the final queue state of every order
(remaining, ``ahead_qty``, resting or not) is recorded; the Rust test
``rust/venue/tests/golden_venue_queue.rs`` and the Python test
``python/tests/test_venue_queue_golden.py`` must reproduce them exactly.

The vectors exercise: EXECUTE pay-down and fills at and through our level;
CANCEL / MODIFY credits from orders known to be ahead and none from orders
behind (ADD after our rest, size-increase MODIFY); the sibling queue (our
own earlier order is ahead of our later one and is served first from one
print); the crossing check with the aggressive-leg exemption and the rule-3b
overlay (an unchanged display is never consumed twice); marketable-ADD
expansion; a duplicate (dropped) event that moves nobody; a cancel.

Usage (from the repo root)::

    PYTHONPATH=python/src python python/tools/make_golden_venue_queue.py [--force]

The file is written with LF line endings.
"""

from __future__ import annotations

import json
import sys
from pathlib import Path
from typing import Any

ROOT = Path(__file__).resolve().parents[2]
sys.path.insert(0, str(ROOT / "python" / "src"))

from iap.core.events import EventType, MarketEvent  # noqa: E402
from iap.execution import (  # noqa: E402
    ChildOrder,
    ExecConfig,
    ExecutionSimulator,
    InstrumentSpec,
    LatencyConfig,
    Liquidity,
    OrderState,
    OrderType,
    VenueSpec,
)

GOLDEN = ROOT / "tests" / "golden" / "expected_venue_queue.json"
#: `order_type` in the golden is the VENUE wire code (`venue::OrderType`,
#: `iap.risk.OrderType`: LIMIT = 2), not the execution simulator's enum.
WIRE_LIMIT = 2
T0 = 1_700_000_000_000_000_000
MS = 1_000_000
INSTRUMENT = 1
VENUE = 1
TICK = 0.01
TAKER_FEE = 0.003
MAKER_REBATE = 0.002

DESCRIPTION = (
    "Rule-4 queue-position golden of the Rust venue simulator (v1.17 B9, review row X-10): "
    "fixed vectors run through the Python execution simulator (the rule-4 reference, "
    "API_TRADING.md section 2) with zero latency. `events` are canonical market events of "
    "instrument 1 on venue 1 (tick 0.01); `actions` happen after the event whose `event_id` is `after_event` "
    "has been processed and before the next one: `submit` places the order (ids are the simulator's own, "
    "in submission order; `order_type` is the venue wire code, 2 = LIMIT; `decision_ts` = that "
    "event's exchange_ts), "
    "`cancel` cancels it. `expected_fills` lists every fill in emission order (`ts` = event "
    "time of a passive fill, the submission time of an aggressive one; `liquidity` taker / "
    "maker); `expected_final` lists every order's remaining quantity, whether it still rests, "
    "and the `ahead_qty` of a resting order. Generated by "
    "python/tools/make_golden_venue_queue.py; replayed byte-for-byte by "
    "rust/venue/tests/golden_venue_queue.rs and python/tests/test_venue_queue_golden.py."
)


def ev(
    seq: int,
    et: EventType,
    side: int,
    price: int,
    qty: int,
    order_id: int,
    *,
    ts: int | None = None,
    trade_id: int = 0,
    sequence: int | None = None,
) -> dict[str, Any]:
    """One canonical event (key order = ``MarketEvent.to_dict``)."""
    t = T0 + seq * MS if ts is None else ts
    return {
        "event_id": seq,
        "instrument_id": INSTRUMENT,
        "venue_id": VENUE,
        "exchange_ts": t,
        "receive_ts": t,
        "sequence": seq if sequence is None else sequence,
        "event_type": int(et),
        "side": side,
        "price_ticks": price,
        "qty": qty,
        "order_id": order_id,
        "trade_id": trade_id,
    }


def add(seq: int, side: int, price: int, qty: int, oid: int, **kw: Any) -> dict[str, Any]:
    return ev(seq, EventType.ADD, side, price, qty, oid, **kw)


def execute(seq: int, side: int, price: int, qty: int, oid: int, **kw: Any) -> dict[str, Any]:
    return ev(seq, EventType.EXECUTE, side, price, qty, oid, **kw)


def cancel(seq: int, side: int, price: int, oid: int, **kw: Any) -> dict[str, Any]:
    return ev(seq, EventType.CANCEL, side, price, 0, oid, **kw)


def modify(seq: int, side: int, price: int, qty: int, oid: int, **kw: Any) -> dict[str, Any]:
    return ev(seq, EventType.MODIFY, side, price, qty, oid, **kw)


def submit(after: int, side: int, qty: int, price: int) -> dict[str, Any]:
    return {
        "after_event": after,
        "submit": {
            "side": side,
            "qty": qty,
            "price_ticks": price,
            "order_type": WIRE_LIMIT,
        },
    }


def cxl(after: int, order_id: int) -> dict[str, Any]:
    return {"after_event": after, "cancel": order_id}


# Shared opening book: bids 2450 x 300 (ids 11: 100, 12: 200), 2449 x 500 (13);
# asks 2452 x 200 (21), 2453 x 400 (22).
def opening() -> list[dict[str, Any]]:
    return [
        add(1, 0, 2450, 100, 11),
        add(2, 0, 2450, 200, 12),
        add(3, 0, 2449, 500, 13),
        add(4, 1, 2452, 200, 21),
        add(5, 1, 2453, 400, 22),
    ]


VECTORS: list[dict[str, Any]] = [
    {
        "name": "execute_paydown_at_and_through_our_level",
        "events": opening()
        + [
            execute(6, 0, 2450, 100, 11),  # ahead 300 -> 200
            execute(7, 0, 2450, 150, 12),  # ahead 200 -> 50
            execute(8, 0, 2450, 50, 12),  # ahead 50 -> 0, budget spent: no fill
            add(9, 0, 2450, 100, 14),  # behind us
            execute(10, 0, 2450, 60, 14),  # ahead 0: fill 60 @ 2450
            cancel(11, 0, 2450, 14),  # behind us: nothing moves
            execute(12, 0, 2449, 40, 13),  # trade THROUGH our bid: fill 40 @ 2450 -> filled
            execute(13, 0, 2449, 100, 13),  # we are gone: nothing
        ],
        "actions": [submit(5, 0, 100, 2450)],
    },
    {
        "name": "cancel_and_modify_credit_only_from_orders_ahead",
        "events": opening()
        + [
            add(6, 0, 2450, 100, 14),  # joins after us: behind
            cancel(7, 0, 2450, 14),  # behind: no credit
            cancel(8, 0, 2450, 11),  # ahead: 300 -> 200
            modify(9, 0, 2450, 120, 12),  # size down 200 -> 120 keeps priority: 200 -> 120
            modify(10, 0, 2450, 500, 12),  # size up: moves to the tail (behind us)
            cancel(11, 0, 2450, 12),  # behind now: no credit (ahead stays 120)
            add(12, 0, 2450, 200, 15),  # behind
            execute(13, 0, 2450, 150, 15),  # pays down 120, fills 30 @ 2450
            modify(14, 0, 2450, 10, 15),  # size down of an order BEHIND us: no credit
            execute(15, 0, 2450, 10, 15),  # fills 10 @ 2450
        ],
        "actions": [submit(5, 0, 50, 2450)],
    },
    {
        "name": "crossing_check_exemption_and_overlay",
        "events": opening()
        + [
            add(
                6, 1, 2451, 40, 23
            ),  # crosses our 2452 bid, but we are exempt (ask 2452 still shown)
            add(7, 1, 2455, 10, 24),  # unrelated; still exempt
            cancel(8, 1, 2452, 21),  # the consumed display goes; best ask 2451 still crosses
            cancel(9, 1, 2451, 23),  # best ask 2453: uncrossed -> exemption ends
            add(10, 1, 2451, 60, 25),  # crossing: fill 60 @ 2452 (our limit), overlay 60
            add(11, 0, 2440, 10, 16),  # display unchanged: no second fill from the same 60
            add(12, 1, 2451, 100, 26),  # level 160, overlay capped 60: pool 100 -> fill 40, filled
        ],
        "actions": [submit(5, 0, 300, 2452)],  # fills 200 @ 2452 aggressively, rests 100
    },
    {
        "name": "sibling_queue_one_print_served_in_order",
        "events": opening()
        + [
            execute(6, 0, 2449, 500, 13),  # first order: ahead 500 -> 0, budget spent
            add(7, 0, 2449, 300, 17),  # behind both
            execute(8, 0, 2449, 300, 17),  # first fills 100, second pays down 100 then fills 50
        ],
        "actions": [submit(5, 0, 100, 2449), submit(5, 0, 50, 2449)],
    },
    {
        "name": "marketable_add_expansion_duplicate_and_cancel",
        "events": opening()
        + [
            add(6, 0, 2453, 150, 18),  # marketable buy: consumes 150 of ask 2452: ahead 200 -> 50
            add(6, 0, 2453, 150, 18, sequence=6),  # retransmitted duplicate: dropped, moves nobody
            execute(7, 1, 2452, 50, 21),  # ahead 50 -> 0, budget spent
            add(8, 0, 2452, 80, 19),  # marketable buy at our level: fill 80 @ 2452
            ev(9, EventType.TRADE, 0, 2452, 80, 0, trade_id=9),  # tape print: ignored
            add(10, 1, 2452, 30, 27),  # behind our remaining 20
        ],
        "actions": [
            submit(5, 1, 100, 2452),
            cxl(9, 1),
        ],  # sell rests behind 200; cancelled before event 10
    },
]


def run_vector(vec: dict[str, Any]) -> tuple[list[dict[str, Any]], list[dict[str, Any]]]:
    """Drive the Python simulator; returns (fills, final states)."""
    config = ExecConfig(
        latency=LatencyConfig(0, 0, 0),
        instruments={INSTRUMENT: InstrumentSpec(INSTRUMENT, TICK)},
        venues={
            VENUE: VenueSpec(
                VENUE, taker_fee_per_share=TAKER_FEE, maker_rebate_per_share=MAKER_REBATE
            )
        },
    )
    sim = ExecutionSimulator(config)
    by_event: dict[int, list[dict[str, Any]]] = {}
    for action in vec["actions"]:
        by_event.setdefault(action["after_event"], []).append(action)
    events = [MarketEvent(**e) for e in vec["events"]]
    assigned: list[int] = []
    for e in events:
        sim.on_event(e)
        for action in by_event.get(e.event_id, []):
            if "submit" in action:
                s = action["submit"]
                oid = sim.submit(
                    ChildOrder(
                        instrument_id=INSTRUMENT,
                        venue_id=VENUE,
                        side=s["side"],
                        type=OrderType.LIMIT,
                        limit_ticks=s["price_ticks"],
                        qty=s["qty"],
                        decision_ts=e.exchange_ts,
                    )
                )
                action["submit"]["order_id"] = oid
                action["submit"]["decision_ts"] = e.exchange_ts
                assigned.append(oid)
            else:
                sim.cancel(action["cancel"], e.exchange_ts)
    # activations / cancels pending after the last event never happen in the
    # Python simulator; every vector ends with an event, so none are pending
    assert not sim._pending and not sim._cancels  # noqa: SLF001
    fills = [
        {
            "order_id": f.order_id,
            "ts": f.ts,
            "qty": f.qty,
            "price_ticks": f.price_ticks,
            "liquidity": "maker" if f.liquidity == Liquidity.MAKER else "taker",
        }
        for f in sim.fills
    ]
    final = []
    for oid in assigned:
        o = sim.orders[oid]
        row: dict[str, Any] = {
            "order_id": oid,
            "remaining": o.remaining,
            "resting": o.state == OrderState.ACTIVE,
        }
        if o.state == OrderState.ACTIVE:
            row["ahead_qty"] = o.ahead_qty
        final.append(row)
    return fills, final


def build() -> dict[str, Any]:
    vectors = []
    for vec in VECTORS:
        vec = json.loads(json.dumps(vec))  # deep copy: run_vector annotates actions
        fills, final = run_vector(vec)
        vectors.append(
            {
                "name": vec["name"],
                "events": vec["events"],
                "actions": vec["actions"],
                "expected_fills": fills,
                "expected_final": final,
            }
        )
    return {
        "x-version": 1,
        "description": DESCRIPTION,
        "instrument_id": INSTRUMENT,
        "venue_id": VENUE,
        "tick_size": TICK,
        "taker_fee_per_share": TAKER_FEE,
        "maker_rebate_per_share": MAKER_REBATE,
        "vectors": vectors,
    }


def main(argv: list[str]) -> int:
    doc = build()
    text = json.dumps(doc, indent=2) + "\n"
    if GOLDEN.exists() and "--force" not in argv:
        if GOLDEN.read_text(encoding="utf-8") == text:
            print(f"{GOLDEN} is current")
            return 0
        print(f"{GOLDEN} exists and would change; pass --force", file=sys.stderr)
        return 1
    GOLDEN.write_text(text, encoding="utf-8", newline="\n")
    n_fills = sum(len(v["expected_fills"]) for v in doc["vectors"])
    print(f"wrote {GOLDEN} ({len(doc['vectors'])} vectors, {n_fills} fills)")
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv[1:]))
