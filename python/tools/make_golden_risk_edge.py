"""Generate the hard-risk EDGE golden: ``tests/golden/expected_risk_edge_decisions.json``
and ``tests/golden/expected_risk_edge_audit.jsonl``.

The main risk golden (``expected_risk_decisions.json``, generated by the Rust
reference) drives ONE engine through one script, so it cannot reach the
branches that need a different engine build or a failing call: a fail-closed
configuration, an engine awaiting bootstrap, a restore, a malformed kill
command — nor the fail-closed branches added after it was pinned. This
second fixture is a list of independent SCENARIOS, each with its own engine,
generated from the Python reference-equivalent port and replayed by all
three languages (``python/tests/test_risk_golden.py``,
``rust/risk/tests/golden_risk.rs``, Java ``RiskGoldenTest``): every order
step's decision / rule / severity must match and the concatenated audit log
must be byte-identical.

Usage (from the repo root)::

    PYTHONPATH=python/src python python/tools/make_golden_risk_edge.py

Both files are written with LF line endings.
"""

